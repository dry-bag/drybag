"""What planning the footprint over the smoke fixture still says.

The fixture is grown rather than generated at smoke time: `stayfixed init --yes` ran on a copy
of it once, and the footprint it wrote was committed back. So the claim this module holds is the
one that can go stale: that planning the footprint over the fixture today has nothing left to
create. `stayfixed.toml` itself was kept exactly as hand-written rather than let that same run
replace it, and deliberately so: a fixture built fresh at smoke time would make the smoke suite
depend on `init` finishing cleanly rather than on a tree already known to satisfy every gate.

**It is not "the fixture is what the shipped templates render".** Measured on a copy: the audits
README is the template's own bytes, while the bug index, the roadmap and `trail.toml` genuinely
differ from the templates, and every one of them comes back `skip_modified` ("create-once, and the
file is already there"), as `stayfixed.toml` does.

**The divergence is the fixture's design, not its drift.** `tests/test_fixtures.py` runs every
gate over this tree and those three files are what the gates read — a bug index listing `BR-001`,
a roadmap carrying the trail listing, a `trail.toml` declaring a state per document. A fixture
regenerated from a clean `init` would carry the templates' empty forms instead (`render_index([],
bug_register(config))` lists no bug at all), so the gates would be checking a project with
nothing in it.
"""

from __future__ import annotations

import shutil
from pathlib import Path

from stayfixed.config.loader import CONFIG_FILE, load
from stayfixed.project.api import project_templates
from stayfixed.scaffold import Verb, plan

ROOT = Path(__file__).resolve().parents[2]
SMOKE = ROOT / "tests" / "fixtures" / "smoke-project"


def test_the_smoke_fixture_is_a_project_init_has_nothing_left_to_create_in(tmp_path: Path) -> None:
    # Mutation (by hand — the fixture is data): delete the fixture's `docs/trail.toml` -> `trail`
    # is planned `create` and the assertion reddens, and the fixture is regenerated by running
    # `stayfixed init --yes` on a copy and committing the result back.
    root = tmp_path / "smoke"
    shutil.copytree(SMOKE, root)
    config = load(root, machine=tmp_path / "absent.toml")
    templates = project_templates(config, document=(root / CONFIG_FILE).read_text("utf-8"))
    planned = plan(root, templates)
    # The walk is stated non-empty first: an empty artifact list would satisfy the assertion
    # below while proving nothing about the fixture at all.
    assert len(templates) >= 5
    assert not [a for a in planned.actions if a.verb is Verb.CREATE]
